/**
 * The closed vocabulary of the shift audit trail: what can happen, why tracking can
 * fail, and why a shift can end. Dependency-free so server code, the admin UI and
 * the driver portal all use the same words.
 *
 * The point of keeping causes this granular is the requirement that tracking
 * failures are never mistaken for intentional actions and no reason is assumed
 * without evidence: "the driver ended the shift" and "we stopped hearing from the
 * phone" are different facts and must never share a label.
 */

export const SHIFT_EVENT_TYPES = [
  // Driver / device actions
  "SHIFT_STARTED",
  "SHIFT_ENDED",
  "TRACKING_STARTED",
  "TRACKING_STOPPED",
  "TRACKING_INTERRUPTED",
  "TRACKING_RESUMED",
  "CONNECTIVITY_LOST",
  "CONNECTIVITY_RESTORED",
  "DEVICE_BOOTED",
  // Generated by the server
  "HEARTBEAT_MISSED",
  "SIGNAL_RESTORED",
  // Access audit: staff opened this shift's log
  "LOG_VIEWED",
] as const;
export type ShiftEventType = (typeof SHIFT_EVENT_TYPES)[number];

/** Event types a phone may submit. Everything else is written only by the server. */
export const DEVICE_EVENT_TYPES: readonly ShiftEventType[] = [
  "SHIFT_STARTED",
  "SHIFT_ENDED",
  "TRACKING_STARTED",
  "TRACKING_STOPPED",
  "TRACKING_INTERRUPTED",
  "TRACKING_RESUMED",
  "CONNECTIVITY_LOST",
  "CONNECTIVITY_RESTORED",
  "DEVICE_BOOTED",
];

export type ShiftActor = "driver" | "admin" | "system" | "device";

/**
 * Why tracking stopped while the shift was still open.
 * NO_SIGNAL_FROM_DEVICE is the one cause the *server* assigns, and it means exactly
 * "we stopped hearing from the phone" - not internet loss, not shutdown, not a
 * killed app: all three look identical from here.
 */
export const TRACKING_CAUSES = [
  "GPS_PERMISSION_DENIED",
  "LOCATION_SERVICES_OFF",
  "DEVICE_SHUTDOWN",
  "TRACKING_SERVICE_STOPPED",
  "NO_LOCATION_FIX",
  "NO_SIGNAL_FROM_DEVICE",
  "UNKNOWN",
] as const;
export type TrackingCause = (typeof TRACKING_CAUSES)[number];

/**
 * Causes that are a loss of signal rather than anything switched off: Location and
 * the permission are both on, the phone simply gets no fix (tunnel, basement car
 * park). Shown as an interruption, but never used to auto-end a shift.
 */
export const SOFT_TRACKING_CAUSES: readonly string[] = ["NO_LOCATION_FIX"];

export function isSoftTrackingCause(cause: string | null | undefined): boolean {
  return !!cause && SOFT_TRACKING_CAUSES.includes(cause);
}

export const CONNECTIVITY_CAUSE = "INTERNET_DISCONNECTED" as const;

export const END_REASONS = [
  "DRIVER_ENDED",
  "SCHEDULE_ELAPSED",
  "TRACKING_LOST_TIMEOUT",
  "SUPERSEDED_BY_NEW_SHIFT",
] as const;
export type EndReason = (typeof END_REASONS)[number];

export function isTrackingCause(v: unknown): v is TrackingCause {
  return typeof v === "string" && (TRACKING_CAUSES as readonly string[]).includes(v);
}

